"""The moving-region jolt check on a card: ``woof hex moving check --lts``.

THE BREAKAGE THIS PREVENTS: a move whose remap leaves the new mesh out of
discrete pressure/buoyancy balance.  Conservative remapping of rho and theta
mass onto changed vertical geometry does not commute with the equation of
state, so the old remap jolted the dynamics after every move (worst 16.2x the
fixed run on this fixture).  The balanced
initialization must keep every move at most 1.5x and conserve dry, theta and
tracer mass to 1e-9, through the production LTS executor with changing
classes, and every balanced move must say in its receipt that it applied.
The previous remap must still fail the same check on the card: a fixture whose
fixed arm is not at rest (a tracer heavy enough to have weight, 2026-10-14)
hides the defect, and then this test would pass with the fix reverted.
"""

from __future__ import annotations

import pytest

cupy = pytest.importorskip("cupy")


def test_balanced_moves_do_not_jolt_and_conserve_on_the_lts_executor(tmp_path):
    from woof.hex import engines
    from woof.hex.moving_jolt_check import run_check

    for spec in (engines.MESH, engines.GEOMETRY):
        path, where = engines.locate(spec)
        if path is None:
            pytest.skip(f"{spec.name} is not available ({where}); the fixture meshes are generated by it")
    receipt = run_check(tmp_path, device="gpu", lts=True)
    verdict = receipt["verdict"]
    assert verdict["passed"], verdict
    assert verdict["balanced_worst_jolt"] <= 1.5
    assert max(verdict["balanced_worst_conservation"].values()) <= 1e-9
    budgets = receipt["results"]["balanced"]["budgets"]
    assert len(budgets) == 3 and all(b["balance"]["applied"] is True for b in budgets)
    assert all(b["balance"]["applied"] is False for b in receipt["results"]["baseline"]["budgets"])
    # the check can see the defect it guards against: the previous remap jolts well past the limit
    assert verdict["baseline_worst_jolt"] > 3 * verdict["limit"], verdict
