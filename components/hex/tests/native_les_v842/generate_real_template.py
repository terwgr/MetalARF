"""Emit test constants/ABI forwarding from the synthetic native frame schema.

No real weather input is decoded or transformed by this source generator.
"""
import json
from pathlib import Path
import sys
import numpy as np

sys.path.insert(0,str(Path(__file__).resolve().parent.parent))
from replay_les_boundary_v842 import cases
from woof.hex.mixing_v842_les import les_boundary_arguments


def generate():
    root=Path(__file__).parent
    spec=les_boundary_arguments();_,values=next(cases())
    rows=[]
    for name,field in spec.items():
        value=values[name]
        dims='&['+','.join(json.dumps(s) for s in field['dims'])+']'
        shape='&['+','.join(map(str,value.shape))+']'
        words='&['+','.join(hex(int(x)) for x in value.ravel(order='F').view('u4'))+']'
        rows.append(f'({json.dumps(name)},{str(field["type"]=="int").lower()},{dims},{shape},{words})')
    (root/'real_template.rs').write_text('// Generated by generate_real_template.py; synthetic test constants only.\n'
        'type Prototype = (&\'static str, bool, &\'static [&\'static str], &\'static [usize], &\'static [u32]);\n'
        'const PROTOTYPES: &[Prototype] = &[\n'+',\n'.join(rows)+'\n];\n')
    count=len(spec)
    (root/'real_invoker.c').write_text('/* Generated ABI forwarding only: pristine replay_les_boundary. */\n'
        'void invoke_les_boundary(void *symbol, void **args) {\n'
        '  typedef void (*Boundary)('+','.join(['void *']*count)+');\n'
        '  ((Boundary)symbol)('+','.join(f'args[{i}]' for i in range(count))+');\n}\n')


if __name__=='__main__':generate()
