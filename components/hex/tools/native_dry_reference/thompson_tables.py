"""Pinned Fortran table generators for source-checkout referee proofs only."""
from __future__ import annotations
from pathlib import Path
import shutil
import subprocess
import tempfile
from typing import Callable
from woof.hex.mpasphys.resources_build import (
    PhysicsResourceError, STRICT_FFLAGS, PINNED_LOG10F_CFLAGS, HOST_MATH_COMPILE,
    HOST_MATH_LINK, _THOMPSON_OBJECTS, THOMPSON_SOURCES, _thompson_expected,
    sha256_file, _copy_verified, fetch, _stage_pinned_log10f, _stage_pinned_host_maths,
    _toolchain, _replace_into, _mkdir, _log,
)


def thompson_generator_commands(fortran: str) -> list[list[str]]:
    """Compile and link commands of the two Thompson generators, in order (run in the build directory)."""
    compile_ = [fortran, *STRICT_FFLAGS]
    units = ("framework_stubs.F90", "mpas_atmphys_functions.F", "mp_radar.F90", "module_mp_thompson.F",
             "atmphys_build_tables_thompson.F", "build_tables.F", "thompson_auxiliary_export.F90")
    commands = [[*compile_, "-c", unit] for unit in units]
    # gfortran's driver compiles C with the same GCC; -D renames cr_log10f so it replaces the C library's.
    commands.append([fortran, *PINNED_LOG10F_CFLAGS, "-c", "cr_log10f.c", "-o", "cr_log10f.o"])
    commands.append(list(HOST_MATH_COMPILE))
    objects = [name + ".o" for name in _THOMPSON_OBJECTS] + ["cr_log10f.o", "thompson_host_math.o", *HOST_MATH_LINK]
    commands.append([*compile_, "-o", "build_tables", *objects, "atmphys_build_tables_thompson.o", "build_tables.o"])
    commands.append([*compile_, "-o", "thompson_auxiliary_export", *objects, "thompson_auxiliary_export.o"])
    return commands


def build_thompson_strict(cache: Path, *, mpas_source: Path | None = None, thompson_tables: Path | None = None,
                          offline: bool = False, log: Callable[[str], None] = _log) -> Path:
    """The four strict MP_THOMPSON_*.DBL tables plus auxiliary.bin, every byte pinned."""
    expected = _thompson_expected()
    final = cache / "thompson-strict" / "tables"
    if all((final / name).is_file() and sha256_file(final / name) == sha for name, sha in expected.items()):
        return final
    if thompson_tables is not None:
        for name, sha in expected.items():
            source = Path(thompson_tables) / name
            if name == "auxiliary.bin" and not source.is_file():
                continue
            if not source.is_file() or sha256_file(source) != sha:
                raise PhysicsResourceError(f"--thompson-tables {thompson_tables}: {name} is absent or is not the "
                                           f"strict native reference's bytes (sha256 {sha})")
            if not ((final / name).is_file() and sha256_file(final / name) == sha):
                _copy_verified(source, final / name, sha)
        if (final / "auxiliary.bin").is_file():
            return final
    fortran = shutil.which("gfortran")
    if fortran is None:
        raise PhysicsResourceError(
            "the Thompson strict tables are generated by GNU Fortran from the pinned MPAS sources and "
            "gfortran is not on PATH; install it, or pass --thompson-tables DIR holding the strict native "
            "reference's MP_THOMPSON_*.DBL and auxiliary.bin")
    build = Path(tempfile.mkdtemp(prefix="build-", dir=_mkdir(cache / "thompson-strict")))
    try:
        for name, (origin, path, sha) in THOMPSON_SOURCES.items():
            fetch(name, origin, path, sha, cache / "sources" / sha / name, mpas_source=mpas_source, offline=offline)
            shutil.copyfile(cache / "sources" / sha / name, build / name)
        native = Path(__file__).resolve().parent / "table_sources"
        for name in ("framework_stubs.F90", "thompson_auxiliary_export.F90"):
            shutil.copyfile(native / name, build / name)
        _stage_pinned_log10f(build)
        _stage_pinned_host_maths(build)
        for name in expected:
            if name != "auxiliary.bin" and (final / name).is_file() and sha256_file(final / name) == expected[name]:
                shutil.copyfile(final / name, build / name)
        log(f"compiling the pinned Thompson sources with {_toolchain(fortran)['fortran_version'] or fortran} "
            "and pinned Thompson host maths / CORE-MATH log10f")
        for command in thompson_generator_commands(fortran):
            subprocess.run(command, cwd=build, check=True)
        if not all((build / name).is_file() for name in expected if name != "auxiliary.bin"):
            log("generating the Thompson strict lookup tables (build_tables; a few minutes, about 350 MB)")
            with (build / "build_tables.log").open("w") as stream:
                subprocess.run([str(build / "build_tables")], cwd=build, stdout=stream, stderr=subprocess.STDOUT,
                               check=True)
        with (build / "auxiliary.log").open("w") as stream:
            subprocess.run([str(build / "thompson_auxiliary_export")], cwd=build, stdout=stream,
                           stderr=subprocess.STDOUT, check=True)
        actual = {name: sha256_file(build / name) for name in expected}
        differing = {name: sha for name, sha in actual.items() if sha != expected[name]}
        if differing:
            toolchain = _toolchain(fortran)
            raise PhysicsResourceError(
                "the Thompson strict tables generated here differ from the strict native reference: "
                + ", ".join(f"{name} sha256 {sha}" for name, sha in sorted(differing.items()))
                + f" (toolchain: {toolchain['fortran_version']}; {toolchain['libc']}). The generators already "
                "pin Thompson host maths and CORE-MATH log10f; this toolchain differs elsewhere, so "
                "pass --thompson-tables DIR holding the reference's bytes")
        for name, sha in expected.items():
            _replace_into(build / name, final / name)
    finally:
        shutil.rmtree(build, ignore_errors=True)
    return final


def build_thompson_aero_auxiliary(cache: Path, tables: Path, ccn_activate: Path,
                                  *, mpas_source: Path | None = None, offline: bool = False,
                                  log: Callable[[str], None] = _log) -> Path:
    """auxiliary.bin for aerosol-aware Thompson, every byte pinned (thompson_aero_v842.AUXILIARY_SHA256).

    thompson_init with is_aerosol_aware, then MPAS's own CCN_ACTIVATE_DATA read
    (mpas_atmphys_init_microphysics.F:251-310), compiled with the strict recipe from
    the pinned sources; ``tables`` holds the four strict MP_THOMPSON_*.DBL the
    initialisation reads.
    """
    from .thompson_aero_v842 import AUXILIARY_SHA256
    final = cache / "thompson-strict" / "aerosol" / "auxiliary.bin"
    if final.is_file() and sha256_file(final) == AUXILIARY_SHA256:
        return final
    fortran = shutil.which("gfortran")
    if fortran is None:
        raise PhysicsResourceError(
            "the aerosol-aware Thompson auxiliary arrays are generated by GNU Fortran from the pinned MPAS "
            "sources and gfortran is not on PATH; install it")
    build = Path(tempfile.mkdtemp(prefix="build-aero-", dir=_mkdir(cache / "thompson-strict")))
    try:
        for name, (origin, path, sha) in THOMPSON_SOURCES.items():
            if name in ("build_tables.F", "atmphys_build_tables_thompson.F"):
                continue
            fetch(name, origin, path, sha, cache / "sources" / sha / name, mpas_source=mpas_source, offline=offline)
            shutil.copyfile(cache / "sources" / sha / name, build / name)
        native = Path(__file__).resolve().parent / "table_sources"
        for name in ("framework_stubs.F90", "thompson_aero_auxiliary_export.F90"):
            shutil.copyfile(native / name, build / name)
        for name in _thompson_expected():
            if name != "auxiliary.bin":
                shutil.copyfile(Path(tables) / name, build / name)
        shutil.copyfile(ccn_activate, build / "CCN_ACTIVATE_DATA")
        _stage_pinned_log10f(build)
        _stage_pinned_host_maths(build)
        compile_ = [fortran, *STRICT_FFLAGS]
        log("generating the aerosol-aware Thompson auxiliary arrays (thompson_init with is_aerosol_aware and "
            "MPAS's CCN_ACTIVATE_DATA read; the pinned CORE-MATH log10f, as the Thompson generators)")
        for unit in ("framework_stubs.F90", "mpas_atmphys_functions.F", "mp_radar.F90", "module_mp_thompson.F",
                     "thompson_aero_auxiliary_export.F90"):
            subprocess.run([*compile_, "-c", unit], cwd=build, check=True)
        subprocess.run([fortran, *PINNED_LOG10F_CFLAGS, "-c", "cr_log10f.c", "-o", "cr_log10f.o"],
                       cwd=build, check=True)
        subprocess.run(list(HOST_MATH_COMPILE), cwd=build, check=True)
        subprocess.run([*compile_, "-o", "thompson_aero_auxiliary_export",
                        *(name + ".o" for name in _THOMPSON_OBJECTS), "cr_log10f.o", "thompson_host_math.o", *HOST_MATH_LINK,
                        "thompson_aero_auxiliary_export.o"], cwd=build, check=True)
        with (build / "auxiliary.log").open("w") as stream:
            subprocess.run([str(build / "thompson_aero_auxiliary_export")], cwd=build, stdout=stream,
                           stderr=subprocess.STDOUT, check=True)
        actual = sha256_file(build / "auxiliary.bin")
        if actual != AUXILIARY_SHA256:
            toolchain = _toolchain(fortran)
            raise PhysicsResourceError(
                f"the aerosol-aware Thompson auxiliary generated here has sha256 {actual}, not the strict native "
                f"reference's {AUXILIARY_SHA256} (toolchain: {toolchain['fortran_version']}; {toolchain['libc']})")
        _replace_into(build / "auxiliary.bin", final)
    finally:
        shutil.rmtree(build, ignore_errors=True)
    return final
