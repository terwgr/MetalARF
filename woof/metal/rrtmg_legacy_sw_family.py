"""Metal engine for legacy WRF RRTMG shortwave (ra_sw_physics = 4).

:class:`MetalSW` is the Metal twin of :class:`woof.core.rrtmg_sw.CudaSW`'s
batched path: ``rrtmg_sw_batched_device`` takes the same argument list
(day columns only, aer_opt = 0 or 3, icld >= 1) and runs the nine ``_b``
kernels of ``woof/core/kernels/rrtmg_sw.cu`` transcribed in
``shaders/rrtmg_legacy_sw_family.metal``.  It returns a dict of
MetalArrays with the CUDA key set; :func:`sw_batched_to_host` adds the
three derived ``*dif`` outputs exactly like the CUDA helper.

The packed coefficient table and its offsets are the CUDA unit's
(:func:`woof.core.rrtmg_sw._pack_cuda_tables`); the offsets are compiled
into ``shaders/rrtmg_legacy_sw_tables.metalh``, and construction refuses a
table set whose packing differs from that header.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from woof.core import rrtmg_sw as _sw
from woof.metal.array import MetalArray, MetalArrayModule

_TABLE_HEADER = (Path(__file__).resolve().parent / "shaders"
                 / "rrtmg_legacy_sw_tables.metalh")
_SPCVMC_WK = 16
_LIQ_ICE_FLAGS = ("inflgsw", "iceflgsw", "liqflgsw")


def table_header(tab) -> str:
    """The Metal offsets header for ``tab`` (packing of the CUDA unit)."""
    _, defines = _sw._pack_cuda_tables(tab)
    return ("#ifndef WOOF_RRTMG_LEGACY_SW_TABLES_METALH\n"
            "#define WOOF_RRTMG_LEGACY_SW_TABLES_METALH\n"
            "// Generated by woof.metal.rrtmg_legacy_sw_family.table_header() from the\n"
            "// production SWTables (same packing as rrtmg_sw._pack_cuda_tables).\n"
            + defines.replace("__uint_as_float(", "as_type<float>(")
            + "#endif\n")


def _host(a, dtype=np.float32):
    if isinstance(a, MetalArray):
        a = a.to_numpy()
    else:
        try:
            import cupy as cp  # noqa: F401 - optional on Metal hosts
            if isinstance(a, cp.ndarray):
                a = cp.asnumpy(a)
        except ImportError:
            pass
    return np.ascontiguousarray(np.asarray(a, dtype=dtype))


class MetalSW:
    """Legacy RRTMG SW engine bound to one :class:`SWTables` and context."""

    def __init__(self, tab=None, xp: MetalArrayModule | None = None):
        self.tab = _sw.load_sw_tables() if tab is None else tab
        if table_header(self.tab) != _TABLE_HEADER.read_text(encoding="ascii"):
            raise ValueError("SW table packing differs from the compiled "
                             "rrtmg_legacy_sw_tables.metalh offsets")
        self.xp = xp or MetalArrayModule()
        self.context = self.xp.context
        packed, _ = _sw._pack_cuda_tables(self.tab)
        self.tab_d = self.xp.asarray(packed.astype(np.float32))
        self.ntab = int(packed.size)
        self.ngb_d = self.xp.asarray(np.asarray(self.tab.ngb, np.int32))
        spec = np.zeros(3 * _sw.NBNDSW, np.int32)
        for i, band in enumerate(range(16, 16 + _sw.NBNDSW)):
            value = self.tab.kg[band].get("layreffr")
            if value is None:
                continue
            spec[i] = int(value)
            spec[_sw.NBNDSW + i] = int(band in (16, 17, 27, 28, 29))
            spec[2 * _sw.NBNDSW + i] = 1
        self.spec_d = self.xp.asarray(spec)

    def batch_column_chunk(self, nlayers):
        return _sw.SW_BATCH_COLUMN_CHUNK

    def _run(self, name, arrays, params, grid):
        return self.context.submit_kernel(
            f"rrtmg_legacy_sw_{name}", arrays, params,
            exact_policy=False, grid_size=int(grid), threads_per_group=128)

    def rrtmg_sw_batched_device(self, ncol, nlay, icld, play, plev, tlay,
                                tlev, tsfc, h2ovmr, o3vmr, co2vmr, ch4vmr,
                                n2ovmr, o2vmr, asdir, asdif, aldir, aldif,
                                coszen, adjes, dyofyr, scon,
                                inflgsw, iceflgsw, liqflgsw,
                                cldfmcl, taucmcl, ssacmcl, asmcmcl,
                                fsfcmcl, ciwpmcl, clwpmcl, cswpmcl,
                                reicmcl, relqmcl, resnmcl, aer_opt=0,
                                column_chunk=None,
                                mcica_layout="gpoint", aerosol=None):
        """Same contract as ``CudaSW.rrtmg_sw_batched_device``; one launch
        sequence over all columns (``column_chunk`` is accepted for
        the shared caller contract). For aer_opt=3, ``aerosol``
        is the same-context Metal tuple ``(ztaua, zasya, zomga)`` produced by
        ``rrtmg_aer3_sw_optics`` and is passed directly into spcvmc."""
        if mcica_layout not in ("gpoint", "column"):
            raise ValueError("mcica_layout must be gpoint or column")
        if aer_opt == 3:
            if aerosol is None or len(aerosol) != 3:
                raise ValueError("aer_opt=3 requires Metal (ztaua, zasya, zomga)")
        elif aer_opt != 0:
            raise NotImplementedError(
                f"aer_opt={aer_opt!r}: the SW composition implements "
                "aer_opt 0 and 3 only -- fails closed")
        elif aerosol is not None:
            raise ValueError("aerosol optics were supplied with aer_opt=0")
        if icld < 1:
            raise NotImplementedError("icld = 0 never occurs; fails closed")
        if int(dyofyr) > 0:
            _sw.earth_sun(dyofyr)
        F, f32, i32 = np.float32, np.float32, np.int32
        nl = _sw._radiation_layer_count(nlay)
        ncol = int(ncol)
        nl1 = nl + 1
        G, B = _sw.NGPTSW, _sw.NBNDSW
        xp = self.xp
        if aerosol is not None:
            for name, value in zip(("ztaua", "zasya", "zomga"), aerosol):
                if (not isinstance(value, MetalArray)
                        or value.shape != (ncol, B, nl)
                        or value.dtype != np.dtype(np.float32)
                        or not value.flags.c_contiguous
                        or value.buffer.context is not self.context):
                    raise TypeError(
                        f"aer_opt=3 {name} must be same-context contiguous "
                        f"float32 Metal {(ncol, B, nl)}")

        def col(a):
            return _host(a).reshape(ncol)

        cz = col(coszen)
        if not bool(np.all(cz > F(0.0))):
            raise ValueError("batched SW is day-columns-only (every coszen "
                             "must be > 0) -- filter night columns first")
        # Host scalar prep: the CUDA engine's elementwise FP32 chains.
        cossza = np.where(cz <= F(1.0e-10), F(1.0e-10), cz)
        adjb = col(adjes) * (col(scon) / _sw.RRSW_SCON)
        adjflux = np.repeat(adjb[:, None], B, axis=1)
        aldir_h, aldif_h = col(aldir), col(aldif)
        asdir_h, asdif_h = col(asdir), col(asdif)
        albdir = np.zeros((ncol, B), f32)
        albdif = np.zeros((ncol, B), f32)
        albdir[:, 0:9] = aldir_h[:, None]
        albdif[:, 0:9] = aldif_h[:, None]
        albdir[:, B - 1] = aldir_h
        albdif[:, B - 1] = aldif_h
        albdir[:, 9:13] = asdir_h[:, None]
        albdif[:, 9:13] = asdif_h[:, None]

        def lay(a, n=nl):
            return xp.asarray(_host(a)[:ncol, :n])

        def mcica(a):
            h = _host(a)
            if mcica_layout == "column":
                h = h[:ncol, :nl, :]
            else:
                h = h[:, :ncol, :nl].transpose(1, 2, 0)
            return xp.asarray(np.ascontiguousarray(h))

        base = {"ncol": ncol, "nl": nl}
        tabp = {**base, "ntab": self.ntab}
        subs = []

        # ---- inatm --------------------------------------------------
        vmr = {k: lay(a) for k, a in (("h2ovmr", h2ovmr), ("co2vmr", co2vmr),
                                      ("o3vmr", o3vmr), ("n2ovmr", n2ovmr),
                                      ("ch4vmr", ch4vmr), ("o2vmr", o2vmr))}
        pdp = xp.empty((ncol, nl), f32)
        coldry = xp.empty((ncol, nl), f32)
        wkl = xp.zeros((ncol, nl, _sw.MXMOL), f32)
        subs.append(self._run("inatm", {"plev": lay(plev, nl1), **vmr,
                                        "pdp": pdp, "coldry": coldry,
                                        "wkl": wkl},
                              {**base, "grav": F(self.tab.grav),
                               "avogad": F(self.tab.avogad)}, ncol * nl))

        # ---- cldprmc ------------------------------------------------
        iceflg = int(iceflgsw)
        cldfmc, taucmc = mcica(cldfmcl), mcica(taucmcl)
        ssacmc, asmcmc = mcica(ssacmcl), mcica(asmcmcl)
        fsfcmc, ciwpmc, clwpmc = mcica(fsfcmcl), mcica(ciwpmcl), mcica(clwpmcl)
        if iceflg == 5:
            cswpmc, resnmc = mcica(cswpmcl), lay(resnmcl)
        else:
            cswpmc = xp.zeros((ncol, nl, G), f32)
            resnmc = xp.zeros((ncol, nl), f32)
        taormc = xp.asarray(taucmc.to_numpy())
        err = xp.zeros((ncol, nl, G), i32)
        subs.append(self._run("cldprmc", {
            "tab": self.tab_d, "ngb": self.ngb_d, "cldfmc": cldfmc,
            "ciwpmc": ciwpmc, "clwpmc": clwpmc, "cswpmc": cswpmc,
            "reicmc": lay(reicmcl), "relqmc": lay(relqmcl),
            "resnmc": resnmc, "taormc": taormc, "taucmc": taucmc,
            "ssacmc": ssacmc, "asmcmc": asmcmc, "fsfcmc": fsfcmc,
            "err": err},
            {**tabp, "inflag": int(inflgsw), "iceflag": iceflg,
             "liqflag": int(liqflgsw)}, ncol * nl * G))

        # ---- setcoef + laytrop/laysolfr -----------------------------
        ints = {k: xp.empty((ncol, nl), i32) for k in
                ("jp", "jt", "jt1", "indself", "indfor", "tflag", "lflag")}
        reals = {k: xp.empty((ncol, nl), f32) for k in
                 ("colh2o", "colco2", "colo3", "coln2o", "colch4", "colo2",
                  "colmol", "co2mult", "selffac", "selffrac", "forfac",
                  "forfrac", "fac00", "fac01", "fac10", "fac11")}
        subs.append(self._run("setcoef", {
            "tab": self.tab_d, "pavel": lay(play), "tavel": lay(tlay),
            "coldry": coldry, "wkl": wkl, **ints, **reals},
            tabp, ncol * nl))
        laytrop = xp.empty((ncol,), i32)
        laysolfr = xp.empty((ncol, B), i32)
        subs.append(self._run("laysolfr", {
            "jp": ints["jp"], "tflag": ints["tflag"], "spec": self.spec_d,
            "laytrop": laytrop, "laysolfr": laysolfr}, base, ncol))

        # ---- taumol + sfluxzen --------------------------------------
        coef = {k: reals[k] for k in
                ("colh2o", "colco2", "colch4", "colo2", "colo3",
                 "fac00", "fac01", "fac10", "fac11")}
        taug = xp.empty((ncol, nl, G), f32)
        taur = xp.empty((ncol, nl, G), f32)
        subs.append(self._run("taumol", {
            "laytrop": laytrop, "tab": self.tab_d, "ngb": self.ngb_d,
            "jp": ints["jp"], "jt": ints["jt"], "jt1": ints["jt1"], **coef,
            "colmol": reals["colmol"], "selffac": reals["selffac"],
            "selffrac": reals["selffrac"], "indself": ints["indself"],
            "forfac": reals["forfac"], "forfrac": reals["forfrac"],
            "indfor": ints["indfor"], "taug": taug, "taur": taur},
            tabp, ncol * nl * G))
        sflux = xp.zeros((ncol, G), f32)   # bands 16/27 leave lower rows 0
        subs.append(self._run("sfluxzen", {
            "laytrop": laytrop, "tab": self.tab_d, "ngb": self.ngb_d,
            "laysolfr": laysolfr, "jp": ints["jp"], "jt": ints["jt"],
            "jt1": ints["jt1"], **coef, "sfluxzen": sflux},
            tabp, ncol * G))

        # ---- spcvmc (WRF zero aerosol or caller-supplied aer_opt=3) ----
        nthr = ncol * G
        nwk = _SPCVMC_WK * nl1 * nthr
        zincflx = xp.empty((ncol, G), f32)
        zouts = {k: xp.empty((ncol, nl1, G), f32) for k in
                 ("zcd", "zcu", "zfd", "zfu", "ztdbt_nodel", "ztdbtc_nodel")}
        if aerosol is None:
            ptaua = xp.zeros((ncol, B, nl), f32)
            pasya = xp.zeros((ncol, B, nl), f32)
            pomga = xp.asarray(np.ones((ncol, B, nl), f32))
        else:
            ptaua, pasya, pomga = aerosol
        subs.append(self._run("spcvmc", {
            "tab": self.tab_d, "ngb": self.ngb_d,
            "palbd": xp.asarray(albdif), "palbp": xp.asarray(albdir),
            "pcldfmc": cldfmc, "ptaucmc": taucmc, "pasycmc": asmcmc,
            "pomgcmc": ssacmc, "ptaormc": taormc,
            "ptaua": ptaua, "pasya": pasya, "pomga": pomga,
            "prmu0": xp.asarray(cossza), "adjflux": xp.asarray(adjflux),
            "sfluxzen": sflux, "taug": taug, "taur": taur,
            "zincflx": zincflx, **zouts, "wk": xp.empty((nwk,), f32)},
            {**tabp, "nwk": nwk}, nthr))

        # ---- accumulation + heating rates ----------------------------
        acc = {k: xp.empty((ncol, nl1), f32) for k in
               ("pbbfd", "pbbfu", "pbbcd", "pbbcu", "pbbfddir", "pbbcddir",
                "puvfd", "puvcd", "puvfddir", "puvcddir",
                "pnifd", "pnicd", "pnifddir", "pnicddir")}
        subs.append(self._run("accum", {"ngb": self.ngb_d,
                                        "zincflx": zincflx, **zouts, **acc},
                              base, ncol * nl1))
        swhr = xp.empty((ncol, nl), f32)
        swhrc = xp.empty((ncol, nl), f32)
        subs.append(self._run("post", {
            "pdp": pdp, "pbbfu": acc["pbbfu"], "pbbfd": acc["pbbfd"],
            "pbbcu": acc["pbbcu"], "pbbcd": acc["pbbcd"],
            "swhr": swhr, "swhrc": swhrc},
            {**base, "heatfac": F(self.tab.heatfac)}, ncol * nl))
        for sub in subs:
            sub.wait()

        code = int(np.bitwise_or.reduce(err.to_numpy().ravel()))
        if code:
            raise ValueError(f"rsw_cldprmc device abort, code {code} "
                             "(mirrors the Fortran STOPs)")
        return {
            "swuflx": acc["pbbfu"], "swdflx": acc["pbbfd"],
            "swuflxc": acc["pbbcu"], "swdflxc": acc["pbbcd"],
            "swdkdir": acc["pbbfddir"], "swdkdirc": acc["pbbcddir"],
            "sibvisdir": acc["puvfddir"], "puvfd": acc["puvfd"],
            "sibnirdir": acc["pnifddir"], "pnifd": acc["pnifd"],
            "swhr": swhr, "swhrc": swhrc,
            "swuflxcln": xp.zeros((ncol, nl1), f32),
            "swdflxcln": xp.zeros((ncol, nl1), f32),
        }

    def rrtmg_sw_batched(self, *args, **kwargs):
        """Device run + host fetch, with the CUDA helper's key set."""
        return sw_batched_to_host(self.rrtmg_sw_batched_device(*args, **kwargs))


def sw_batched_to_host(out):
    """Numpy copies plus the derived swdkdif/sibvisdif/sibnirdif."""
    h = {k: v.to_numpy() for k, v in out.items()}
    h["swdkdif"] = h["swdflx"] - h["swdkdir"]
    h["sibvisdif"] = h["puvfd"] - h["sibvisdir"]
    h["sibnirdif"] = h["pnifd"] - h["sibnirdir"]
    del h["puvfd"], h["pnifd"]
    return h
