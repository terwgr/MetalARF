"""Device-resident sunlit RRTMG SW solver stages for MPAS v8.4.2.

The caller selects sunlit columns and supplies the native prepared arrays.
This component does not register a complete native radiation slot.
"""
from __future__ import annotations
import numpy as np
from ..metal_dynamics_v841 import _arrays, _context, _require
from .metal_tendencies_v842 import _launch
from .rrtmg_sw_v842 import LAYREF, SCALAR_BITS


def solve_sunlit(*, tables, layers, interfaces, cosine, albedo, controls, mcica,
                 cloudflag, iceflag, aerosol=None, _stage_probe=False):
    """Run one already-compacted all-sunlit batch; no weather fields visit host.

    Each column's KISS cloud state has already been generated by the native
    wrapper. Supported cloud and ice selectors are those generated by that
    wrapper. Device fatal flags are checked before returning fluxes.
    """
    if len(layers.shape)!=3 or layers.shape[0]!=15:
        raise ValueError('MPAS SW solver needs 15 prepared layer fields')
    _,nc,nl=layers.shape
    if nc<1 or nl<4 or cloudflag not in (2,3,4,5) or iceflag not in (3,4,5):
        raise ValueError('MPAS SW solver requires sunlit columns, four levels and native cloud flags')
    context=_context(layers); nl1=nl+1;G=112;B=14
    values={'layers':layers,'interfaces':interfaces,'cosine':cosine,'albedo':albedo,'controls':controls,'mcica':mcica,'tables':tables.packed,'ngb':tables.ngb}
    shapes={'layers':(15,nc,nl),'interfaces':(2,nc,nl1),'cosine':(nc,),'albedo':(nc,),'controls':(4,),'mcica':(8,nc,nl,G),'tables':(tables.packed.size,),'ngb':(G,)}
    for name,value in values.items():
        _require(name,value,np.int32 if name=='ngb' else np.float32,shapes[name])
        if _context(value) is not context:raise ValueError(f'{name} belongs to another context')
    if aerosol is not None:
        if len(aerosol)!=3:raise ValueError('MPAS SW aerosol optics need tau, asymmetry and albedo')
        for value in aerosol:
            _require('aerosol optics',value,np.float32,(nc,B,nl))
            if _context(value) is not context:raise ValueError('aerosol optics belongs to another context')
    if 4*nc*(45*nl*G+150*nl+200)>context.recommended_working_set_size:
        raise MemoryError('MPAS SW sunlit workspace exceeds Metal working set')
    xp=_arrays(context);f=np.float32;i=np.int32
    scalar=lambda name:np.asarray(SCALAR_BITS[name],np.uint32).view(np.float32)[()]
    def run(name,count,arrays,params):
        kernel='hexv842_sw_sfluxzen_f32' if name=='sfluxzen' else 'rrtmg_legacy_sw_'+name
        context.submit_kernel(kernel,arrays,params,exact_policy=False,grid_size=int(count),threads_per_group=128)
    base=dict(ncol=i(nc),nl=i(nl));tabp={**base,'ntab':i(tables.packed.size)}
    prmu0=xp.empty((nc,),f);adjflux=xp.empty((nc,B),f);albdir=xp.empty((nc,B),f);albdif=xp.empty((nc,B),f)
    _launch('hexv842_sw_solver_inputs_f32',nc,context,dict(cosine=cosine,albedo=albedo,controls=controls,prmu0=prmu0,adjflux=adjflux,albdir=albdir,albdif=albdif),dict(nc=i(nc)))
    pdp=xp.empty((nc,nl),f);coldry=xp.empty((nc,nl),f);wkl=xp.zeros((nc,nl,38),f)
    run('inatm',nc*nl,dict(plev=interfaces[0],h2ovmr=layers[2],o3vmr=layers[3],co2vmr=layers[4],ch4vmr=layers[5],n2ovmr=layers[6],o2vmr=layers[7],pdp=pdp,coldry=coldry,wkl=wkl),{**base,'grav':scalar('con/grav'),'avogad':scalar('con/avogad')})
    cldfmc=mcica[0];ciwpmc=mcica[1];clwpmc=mcica[2];cswpmc=mcica[3]
    taucmc=mcica[4].copy();ssacmc=mcica[5].copy();asmcmc=mcica[6].copy();fsfcmc=mcica[7].copy();taormc=taucmc.copy()
    err=xp.zeros((nc,nl,G),i)
    run('cldprmc',nc*nl*G,dict(tab=tables.packed,ngb=tables.ngb,cldfmc=cldfmc,ciwpmc=ciwpmc,clwpmc=clwpmc,cswpmc=cswpmc,reicmc=layers[12],relqmc=layers[13],resnmc=layers[14],taormc=taormc,taucmc=taucmc,ssacmc=ssacmc,asmcmc=asmcmc,fsfcmc=fsfcmc,err=err),{**tabp,'inflag':i(cloudflag),'iceflag':i(iceflag),'liqflag':i(1)})
    ints={k:xp.empty((nc,nl),i) for k in ('jp','jt','jt1','indself','indfor','tflag','lflag')}
    reals={k:xp.empty((nc,nl),f) for k in ('colh2o','colco2','colo3','coln2o','colch4','colo2','colmol','co2mult','selffac','selffrac','forfac','forfrac','fac00','fac01','fac10','fac11')}
    run('setcoef',nc*nl,dict(tab=tables.packed,pavel=layers[0],tavel=layers[1],coldry=coldry,wkl=wkl,**ints,**reals),tabp)
    spec=np.zeros(3*B,np.int32)
    for j,band in enumerate(range(16,30)):
        if band in LAYREF:
            spec[j]=LAYREF[band];spec[B+j]=int(band in (16,17,27,28,29));spec[2*B+j]=1
    laytrop=xp.empty((nc,),i);laysolfr=xp.empty((nc,B),i)
    run('laysolfr',nc,dict(jp=ints['jp'],tflag=ints['tflag'],spec=xp.asarray(spec),laytrop=laytrop,laysolfr=laysolfr),base)
    coef={k:reals[k] for k in ('colh2o','colco2','colch4','colo2','colo3','fac00','fac01','fac10','fac11')}
    taug=xp.empty((nc,nl,G),f);taur=xp.empty((nc,nl,G),f)
    run('taumol',nc*nl*G,dict(laytrop=laytrop,tab=tables.packed,ngb=tables.ngb,jp=ints['jp'],jt=ints['jt'],jt1=ints['jt1'],**coef,colmol=reals['colmol'],selffac=reals['selffac'],selffrac=reals['selffrac'],indself=ints['indself'],forfac=reals['forfac'],forfrac=reals['forfrac'],indfor=ints['indfor'],taug=taug,taur=taur),tabp)
    sflux=xp.zeros((nc,G),f)
    run('sfluxzen',nc*G,dict(laytrop=laytrop,tab=tables.packed,ngb=tables.ngb,laysolfr=laysolfr,jp=ints['jp'],jt=ints['jt'],jt1=ints['jt1'],**coef,sfluxzen=sflux),tabp)
    zinc=xp.empty((nc,G),f);zouts={k:xp.empty((nc,nl1,G),f) for k in ('zcd','zcu','zfd','zfu','ztdbt_nodel','ztdbtc_nodel')}
    if aerosol is None:
        ptaua=xp.zeros((nc,B,nl),f);pasya=xp.zeros((nc,B,nl),f);pomga=xp.empty((nc,B,nl),f);pomga.fill(1.)
    else:ptaua,pasya,pomga=aerosol
    nwk=16*nl1*nc*G
    run('spcvmc',nc*G,dict(tab=tables.packed,ngb=tables.ngb,palbd=albdif,palbp=albdir,pcldfmc=cldfmc,ptaucmc=taucmc,pasycmc=asmcmc,pomgcmc=ssacmc,ptaormc=taormc,ptaua=ptaua,pasya=pasya,pomga=pomga,prmu0=prmu0,adjflux=adjflux,sfluxzen=sflux,taug=taug,taur=taur,zincflx=zinc,**zouts,wk=xp.empty((nwk,),f)),{**tabp,'nwk':i(nwk)})
    acc={k:xp.empty((nc,nl1),f) for k in ('pbbfd','pbbfu','pbbcd','pbbcu','pbbfddir','pbbcddir','puvfd','puvcd','puvfddir','puvcddir','pnifd','pnicd','pnifddir','pnicddir')}
    run('accum',nc*nl1,dict(ngb=tables.ngb,zincflx=zinc,**zouts,**acc),base)
    swhr=xp.empty((nc,nl),f);swhrc=xp.empty((nc,nl),f)
    run('post',nc*nl,dict(pdp=pdp,pbbfu=acc['pbbfu'],pbbfd=acc['pbbfd'],pbbcu=acc['pbbcu'],pbbcd=acc['pbbcd'],swhr=swhr,swhrc=swhrc),{**base,'heatfac':scalar('con/heatfac')})
    code=int(np.bitwise_or.reduce(err.to_numpy().ravel()))
    if code:raise ValueError(f'MPAS SW cloud optics fatal status {code}')
    out=dict(swuflx=acc['pbbfu'],swdflx=acc['pbbfd'],swuflxc=acc['pbbcu'],swdflxc=acc['pbbcd'],swdkdir=acc['pbbfddir'],swhr=swhr,swhrc=swhrc)
    if _stage_probe: out['_debug']=dict(pdp=pdp,coldry=coldry,**ints,**reals,taug=taug,taur=taur,sflux=sflux,zinc=zinc,**zouts)
    return out
