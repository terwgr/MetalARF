#!/usr/bin/env python3
"""Translate the CUDA cu_physics=6 Tiedtke unit to a Metal kernel.

The routines in tiedtke_routines.cuh are carried over statement for
statement: address spaces, reference parameters and the float helpers change
and nothing else.  Run from the repository root with the data companion on
PYTHONPATH.
"""
from pathlib import Path
import json
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools/mp28_metal"))
sys.path.insert(0, str(ROOT))
from parse import split_top, def_name  # noqa: E402

SHADERS = ROOT / "woof/metal/shaders"
SKIP = {"tk_add", "tk_sub", "tk_mul", "tk_div", "tk_min", "tk_max", "tk_abs",
        "tk_powi", "TkArena", "TkArray", "tiedtke_column"}
LEVEL_INPUTS = ("u3d", "v3d", "w", "t3d", "qv3d", "qc3d", "qi3d", "pi3d",
                "rho3d", "qvften", "qvpblten", "dz8w", "pcps", "p8w", "xland",
                "qfx", "znu")
OUTPUTS = ("rthcuten", "rqvcuten", "rqccuten", "rqicuten", "rucuten",
           "rvcuten", "raincv", "pratec")


def preprocess():
    from woof.core import kernels
    result = subprocess.run(
        ["clang++", "-E", "-P", "-std=c++17", "-x", "c++", "-"],
        input=kernels.module_source("tiedtke").encode(),
        capture_output=True, check=True)
    return split_top(result.stdout.decode())


def convert(item):
    item = item.replace("__device__ ", "").replace("static constexpr",
                                                  "static constant constexpr")
    item = re.sub(r"\binline\s+", "", item)
    item = re.sub(r"(?<![\w&])(float|int)\s*&", r"thread \1 &", item)
    return item.replace("sqrtf(", "cu_sqrt(")


def kernel_text():
    names = list(LEVEL_INPUTS)
    lines = ["kernel void tiedtke_column(",
             "    constant TiedtkeColumnResources &r [[buffer(0)]],",
             "    constant TiedtkeColumnParams &p [[buffer(1)]],",
             "    uint gid [[thread_position_in_grid]])", "{"]
    for n in names:
        lines.append(f"    device const float *{n} = r.{n};")
    for n in OUTPUTS:
        lines.append(f"    device float *{n} = r.{n};")
    lines += ["    device int *cu_act_flag = r.cu_act_flag;",
              "    device float *workspace_f = r.workspace_f;",
              "    device int *workspace_i = r.workspace_i;",
              "    device bool *workspace_b = (device bool *)r.workspace_b;",
              "    const float dt = p.dt;"]
    for n in ("itimestep", "stepcu", "nz", "ncol", "f_qc", "f_qi",
              "force_continue"):
        lines.append(f"    const int {n} = p.{n};")
    lines.append("    int c = int(gid);")
    return "\n".join(lines)


def kernel(items):
    src = next(i for i in items if def_name(i) == "tiedtke_column")
    body = src[src.index("{") + 1:src.rindex("}")]
    body = body.replace("int c = blockIdx.x * blockDim.x + threadIdx.x;", "")
    body = re.sub(r"\bint\* activity = ", "device int *activity = ", body)
    body = re.sub(r"\bTkArena arena = \{", "TkArena arena = {", body)
    return kernel_text() + body + "}\n"


def signature():
    resources = [[n, "float", "read"] for n in LEVEL_INPUTS]
    resources += [[n, "float", "read_write"] for n in OUTPUTS]
    resources += [["cu_act_flag", "int32", "read_write"],
                  ["workspace_f", "float", "read_write"],
                  ["workspace_i", "int32", "read_write"],
                  ["workspace_b", "uint32", "read_write"]]
    parameters = [["dt", "float32"]] + [[n, "int32"] for n in (
        "itimestep", "stepcu", "nz", "ncol", "f_qc", "f_qi", "force_continue")]
    return dict(
        name="tiedtke_column", cuda_symbol="tiedtke_column",
        module="tiedtke_family",
        source="woof/metal/shaders/tiedtke_family.metal",
        cuda_source="woof/core/kernels/tiedtke.cu",
        resources=resources,
        shapes={r[0]: [["any_1d"]] for r in resources},
        parameters=parameters, threads_per_group=32, layout_version=1,
        arithmetic_policies=["soft32-rn-nonftz"])


def main():
    items = preprocess()
    out = []
    for item in items:
        name = def_name(item)
        if name in SKIP or not (name or "").startswith("tk_"):
            continue
        out.append(convert(item))
    # Forward declarations and definitions share one translation order.
    text = ("// Generated by tools/cumulus_metal/generate_tiedtke.py from "
            "tiedtke_routines.cuh; do not edit.\n"
            '#pragma clang diagnostic ignored "-Wunused-variable"\n'
            '#pragma clang diagnostic ignored "-Wparentheses-equality"\n'
            + "\n".join(out) + "\n")
    (SHADERS / "tiedtke_fragment.metalh").write_text(text)
    (SHADERS / "tiedtke_family.metal").write_text(
        "// Generated by tools/cumulus_metal/generate_tiedtke.py; do not edit.\n"
        "#include <metal_stdlib>\n"
        '#include "tiedtke_family_bindings.metalh"\n'
        '#include "tiedtke_support.metalh"\n'
        '#include "tiedtke_fragment.metalh"\n'
        "using namespace metal;\n" + kernel(items))
    (ROOT / "woof/metal/signature_fragments/tiedtke_family.json").write_text(
        json.dumps({"kernels": [signature()]}, indent=2) + "\n")


if __name__ == "__main__":
    main()
