#!/usr/bin/env python3
"""Translate woof/core/kernels/lightning.cu into its Metal shader and signature fragment.

Each kernel body is carried over statement for statement. Only the CUDA
builtins change spelling: thread index, atomicExch (all writers store a
constant), fmaxf/fminf, __int_as_float, and sqrtf through the soft binary32
square root. Run after any change to lightning.cu.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "woof/core/kernels/lightning.cu"
SHADER = ROOT / "woof/metal/shaders/lightning_family.metal"
FRAGMENT = ROOT / "woof/metal/signature_fragments/lightning_family.json"

PLANE = ["ny", "nx"]
SHAPES = {
    "summary": [["2"]], "invalid": [["1"]], "top": [PLANE], "ht": [PLANE],
    "land": [PLANE], "lat": [PLANE], "lon": [PLANE],
    "inputnum": [["12", "ny", "nx"]], "inputden": [["12", "ny", "nx"]],
}
VOLUME = [["nz", "ny", "nx"]]
PRELUDE = """// Generated by tools/lightning_metal/generate.py from woof/core/kernels/lightning.cu.
#include <metal_stdlib>
#include "lightning_patch_bindings.metalh"
#include "lightning_columns_bindings.metalh"
#include "soft_binary32.metalh"
#include "soft_binary64.metalh"
#include "soft_gfk_pow.metalh"

using namespace metal;

static inline float gfk_pow(float x, float y) { return as_type<float>(soft_gfk_pow_bits(as_type<uint>(x), as_type<uint>(y))); }
static inline float sqrtf(float x) { return as_type<float>(soft32_sqrt(as_type<uint>(x))); }
static inline float fmaxf(float a, float b) { return fmax(a, b); }
static inline float fminf(float a, float b) { return fmin(a, b); }
"""


def kernels(text: str):
    pattern = re.compile(r'extern "C" __global__ void (\w+)\(([^)]*)\)\s*\{')
    for match in pattern.finditer(text):
        depth, end = 1, match.end()
        while depth:
            depth += {"{": 1, "}": -1}.get(text[end], 0)
            end += 1
        params = [" ".join(p.split()) for p in match.group(2).replace("\n", " ").split(",")]
        yield match.group(1), [p for p in params if p], text[match.end():end - 1]


def split_param(decl: str):
    pointer = "*" in decl
    tokens = re.findall(r"[A-Za-z_]\w*", decl)
    return tokens[-1], [t for t in tokens[:-1] if t != "const"][0], pointer, "const" in tokens


def translate(name, params, body):
    title = "".join(part.title() for part in name.split("_"))
    resources, scalars, alias = [], [], []
    for decl in params:
        field, ctype, pointer, const = split_param(decl)
        if pointer:
            storage = "int32" if ctype == "int" else "float"
            resources.append([field, storage, "read" if const else "read_write"])
            alias.append(f"    device {'const ' if const else ''}{ctype}* {field} = r.{field};")
        else:
            scalars.append([field, "int32" if ctype == "int" else "float32"])
            alias.append(f"    {ctype} {field} = prm.{field};")
    body = body.replace("blockIdx.x*blockDim.x+threadIdx.x", "int(tid)")
    body = body.replace("blockIdx.x || threadIdx.x", "tid")
    body = re.sub(r"atomicExch\((\w+),(\d)\)", r"\1[0]=\2", body)
    body = body.replace("__int_as_float(", "as_type<float>(")
    shader = (f"kernel void {name}(constant {title}Resources &r [[buffer(0)]],\n"
              f"    constant {title}Params &prm [[buffer(1)]],\n"
              f"    uint tid [[thread_position_in_grid]]) {{\n"
              + "\n".join(alias) + body + "}\n")
    shapes = {}
    for field, storage, _ in resources:
        shapes[field] = SHAPES.get(field, [["ny", "nx"]] if field in ("ic", "cg", "icc", "cgc", "lpi") else VOLUME)
    fragment = {
        "name": name, "module": "lightning_family", "source": "woof/metal/shaders/lightning_family.metal",
        "cuda_source": "woof/core/kernels/lightning.cu", "cuda_symbol": name,
        "resources": resources, "shapes": shapes, "parameters": scalars,
        "threads_per_group": 128, "layout_version": 1, "arithmetic_policies": ["default"],
    }
    return shader, fragment


def main():
    shaders, fragments = [], []
    for name, params, body in kernels(SOURCE.read_text()):
        shader, fragment = translate(name, params, body)
        shaders.append(shader)
        fragments.append(fragment)
    SHADER.write_text(PRELUDE + "\n" + "\n".join(shaders), encoding="utf-8")
    FRAGMENT.write_text(json.dumps({"kernels": fragments}, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
