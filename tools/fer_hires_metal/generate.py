#!/usr/bin/env python3
"""Translate the Ferrier-Aligo CUDA unit (fer_hires.cu) to Metal.

    python tools/fer_hires_metal/generate.py

The unit is preprocessed as the loader hands it to nvrtc and the definitions
its three kernels reach are translated statement for statement. Binary32 values
travel as soft32 words (F) and binary64 values as Soft8; the pinned float math
comes from woof/metal/shaders/fer_hires_support.metalh.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools/mp28_metal"))
sys.path.insert(0, str(ROOT))
from translate import convert_function_item  # noqa: E402
import generate as g  # noqa: E402

SHADERS = ROOT / "woof/metal/shaders"
KERNELS = ("fer_hires_init_tables", "fer_hires_init_scalars", "fer_hires_column")
PROVIDED = {"gfk_exp", "gfk_log", "gfk_pow"}


def as_words(text):
    """The unit's binary32 values travel as F, the soft32 word type."""
    # as_type<float> reinterprets a literal's word; it is not a value of the unit.
    text = re.sub(r"as_type\s*<\s*float\s*>", "AS_TYPE_FLOAT", text)
    return re.sub(r"\bfloat\b", "F", text).replace("AS_TYPE_FLOAT", "as_type<float>")


def device_pointers(text):
    """Table pointers derived from the device buffer keep its address space."""
    return re.sub(r"(?<!device )(const )?F \* (\w+) = tab\b", r"device \1F * \2 = tab", text)


def convert_kernel(item):
    name = g.kernel_info(item)[0]
    # The WRF domain id would shadow the thread index.
    item = re.sub(r"\bgid\b", "domain_id", item)
    item = re.sub(r"blockIdx\s*\.\s*x\s*!=\s*0\s*\|\|\s*threadIdx\s*\.\s*x\s*!=\s*0",
                  "gid != 0", item)
    # The pressure parameter would shadow the Params block in the wrapper.
    item = re.sub(r"\bp\b", "pressure", item)
    text, params = g.convert_kernel(item, name, "fer_hires", [])
    text = re.sub(r"device (const )?float \*(\w+) = r\.(\w+);",
                  r"device \1F *\2 = (device \1F *)r.\3;", text)
    text = re.sub(r"const float (\w+) = p\.(\w+);", r"F \1 = F(p.\2);", text)
    return device_pointers(as_words(text)), params


def signature(name, params):
    resources, shapes, parameters = [], {}, []
    for p in params:
        if p["pointer"]:
            resources.append([p["name"], "float", "read" if p["const"] else "read_write"])
            shapes[p["name"]] = [["any_1d"]]
        else:
            parameters.append([p["name"], "float32" if p["base"] == "float" else "int32"])
    if not parameters:
        # A Metal parameter block cannot be empty; the launch passes its thread count.
        parameters.append(["threads", "int32"])
    return {"name": name, "cuda_symbol": name, "module": "fer_hires_family",
            "source": "woof/metal/shaders/fer_hires_family.metal",
            "cuda_source": "woof/core/kernels/fer_hires.cu", "resources": resources,
            "shapes": shapes, "parameters": parameters, "threads_per_group": 32,
            "layout_version": 1,
            "arithmetic_policies": ["soft32-rn-nonftz", "soft64-rn-bit-ops", "portable-libm64"]}


def main():
    items = [re.sub(r"\breal\b", "float", i) for i in g.items_of("fer_hires", "461")
             if g.def_name(i) not in PROVIDED]
    reached, _ = g.closure(items, list(KERNELS))
    helpers, kernels, signatures = [], [], []
    for item in reached:
        kind = g.kind_of(item)
        name = g.def_name(item)
        if kind == "kernel":
            text, params = convert_kernel(item)
            kernels.append((KERNELS.index(name), text))
            signatures.append((KERNELS.index(name), signature(name, params)))
        elif kind == "function":
            helpers.append(device_pointers(as_words(convert_function_item(item))))
        elif kind == "table":
            helpers.append(as_words(g.convert_table(item)))
    header = "// Generated by tools/fer_hires_metal/generate.py; do not edit.\n"
    (SHADERS / "fer_hires_fragment.metalh").write_text(
        header + '#include "fer_hires_support.metalh"\n#pragma clang fp contract(off)\n'
        "namespace fer_hires {\n" + "\n".join(helpers) + "\n}\n")
    (SHADERS / "fer_hires_family.metal").write_text(
        header + '#include <metal_stdlib>\n#include "fer_hires_fragment.metalh"\n'
        '#include "fer_hires_family_bindings.metalh"\n\n'
        + "\n\n".join(t for _, t in sorted(kernels)) + "\n")
    (ROOT / "woof/metal/signature_fragments/fer_hires_family.json").write_text(
        json.dumps({"kernels": [s for _, s in sorted(signatures)]}, indent=2) + "\n")


if __name__ == "__main__":
    main()
