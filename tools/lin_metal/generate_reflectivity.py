#!/usr/bin/env python3
"""Translate Purdue Lin's REFL_10CM column (lin_refl.cu over refl.cu) to Metal.

    python tools/lin_metal/generate_reflectivity.py

The binary64 radar chains run on the soft64 helpers; the radar_init products
(five size/weight tables and seven scalars) arrive as binary64 words.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools/mp28_metal"))
sys.path.insert(0, str(ROOT))
import generate as g  # noqa: E402
from translate import map_types, rewrite_division, tokenize, untok  # noqa: E402

STEM = "lin_refl_family"
KERNEL = "refl10cm_lin_column"
# radar_init scalars the kernel takes by value, in launch order.
SCALARS = ("k_w", "m_w0_re", "m_w0_im", "m_i0_re", "m_i0_im", "xam_g", "n0_g")


def main():
    items = [re.sub(r"\breal\b", "float", it) for it in g.items_of("lin_refl", "461")]
    reached, _ = g.closure(items, [KERNEL])
    helpers, kernel = [], None
    for it in reached:
        kind = g.kind_of(it)
        if kind == "kernel":
            kernel = it
        elif kind == "struct":
            helpers.append(g.convert_struct(it))
        elif kind == "table":
            helpers.append(g.convert_table(it))
        else:
            helpers.append(g.convert_function_item(it))
    # The pressure parameter would shadow the Params block in the wrapper.
    kernel = re.sub(r"\bp\b", "pressure", kernel)
    text, params = g.convert_kernel(kernel, KERNEL, "aa_lin_refl", [])
    for index, name in enumerate(SCALARS):
        if "= p.%s;" % name not in text:
            raise ValueError("lin_refl.cu changed: " + name)
        text = text.replace("= p.%s;" % name,
                            "= Soft8::fromBits(r.radar_constants[%d]);" % index)
    text = re.sub(r"(?<!device )const Soft8 \* (xxds|xdts|xxdg|xdtg|simpson) =",
                  r"device const Soft8 * \1 =", text)
    resources, shapes, parameters = [], {}, []
    for p in params:
        if p["pointer"]:
            resources.append([p["name"], "float64_bits" if p["base"] == "double" else "float",
                              "read" if p["const"] else "read_write"])
            shapes[p["name"]] = [["any_1d"]]
        elif p["base"] != "double":
            parameters.append([p["name"], "int32"])
    resources.append(["radar_constants", "float64_bits", "read"])
    shapes["radar_constants"] = [[len(SCALARS)]]
    wrappers = """
static inline Soft8 pow(Soft8 x, Soft8 y) { return glibc_pow(x,y); }
static inline Soft8 exp(Soft8 x) { return glibc_exp(x); }
static inline Soft8 log(Soft8 x) { return glibc_log(x); }
static inline Soft8 log10(Soft8 x) { return aa_refl::thompson_aa_log10(x); }
static inline Soft8 hypot(Soft8 x, Soft8 y) { return aa_refl::thompson_aa_hypot(x,y); }
static inline Soft8 atan2(Soft8 y, Soft8 x) { return aa_refl::thompson_aa_atan2(y,x); }
"""
    shaders = ROOT / "woof/metal/shaders"
    header = "// Generated by tools/lin_metal/generate_reflectivity.py; do not edit.\n"
    (shaders / "lin_refl_fragment.metalh").write_text(
        header + "#pragma clang fp contract(off)\nnamespace aa_lin_refl {\n" + wrappers
        + "\n".join(helpers) + "\n}\n")
    (shaders / (STEM + ".metal")).write_text(
        header + '#include <metal_stdlib>\n#include "thompson_aerosol_soft8.metalh"\n'
        '#include "thompson_aerosol_refl_fragment.metalh"\n#include "lin_refl_fragment.metalh"\n'
        '#include "%s_bindings.metalh"\n' % STEM + text + "\n")
    signature = {"name": KERNEL, "cuda_symbol": KERNEL, "module": STEM,
                 "source": "woof/metal/shaders/%s.metal" % STEM,
                 "cuda_source": "woof/core/kernels/lin_refl.cu", "resources": resources,
                 "shapes": shapes, "parameters": parameters, "threads_per_group": 32,
                 "layout_version": 1, "arithmetic_policies": g.POLICIES}
    (ROOT / "woof/metal/signature_fragments" / (STEM + ".json")).write_text(
        json.dumps({"kernels": [signature]}, indent=2) + "\n")


if __name__ == "__main__":
    main()
