#!/usr/bin/env python3
"""Translate the GSD diagnostics CUDA units into one Metal shader and its signatures.

Sources: gsd_diagnostics.cu, gsd_helicity.cu with gsd_helicity_helpers.cuh,
gsd_hail_bins.cuh, and gfk_log10 from glibc_flt32_extra.cuh. Statements are
carried over unchanged. Only spellings change: address spaces, `real`, the
thread index, the float32 libm names (soft glibc ports), and the hail size
routine's binary64 code, which runs on the integer soft binary64 type
(`double` -> HailR8, double literals -> exact bit words, glibc_pow/glibc_exp
-> soft glibc). Run after any change to those sources.
"""
from __future__ import annotations

import json
import re
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
KERNELS = ROOT / "woof/core/kernels"
SHADER = ROOT / "woof/metal/shaders/gsd_diagnostics_family.metal"
FRAGMENT = ROOT / "woof/metal/signature_fragments/gsd_diagnostics_family.json"
SKIP = {"gsd_hail_probe"}

PLANE = [["ny", "nx"]]
MASS = [["nz", "ny", "nx"]]
WLEVEL = [["nz+1", "ny", "nx"]]
SHAPES = {
    "u": [["nz", "ny", "nx+1"]], "v": [["nz", "ny+1", "nx"]],
    "msfu": [["ny", "nx+1"]], "msfv": [["ny+1", "nx"]],
    "phb": [["nz+1"], ["nz+1", "ny", "nx"]], "thb": [["nz"], ["nz", "ny", "nx"]],
    "fnm": [["any_1d"]], "fnp": [["any_1d"]], "znw": [["any_1d"]], "dn": [["any_1d"]], "dnw": [["any_1d"]],
    "ma": [["1"]], "mb": [["1"]],
}
for _name in ("w", "ph", "pw"):
    SHAPES[_name] = WLEVEL
for _name in ("thp", "p", "alt", "qv", "qc", "qr", "qi", "qs", "qg", "qh", "density", "temperature",
              "rho", "rv", "refl", "qcbl", "cfbl"):
    SHAPES[_name] = MASS
PLANE_BY_LENGTH = {"a", "b", "out"}  # gsd_lightning3 planes: any 2-D extent
PRELUDE = """// Generated by tools/gsd_metal/generate.py from the GSD CUDA units.
#include <metal_stdlib>
%(includes)s
#include "soft_binary32.metalh"
#include "soft_binary64.metalh"
#include "soft_gfk_log.metalh"
#include "soft_gfk_exp.metalh"
#include "soft_gfk_pow.metalh"
#include "hailcast_support.metalh"

using namespace metal;

#define G 9.81f
#define I3(k, j, i, ny, nx)  ((size_t)(k) * (ny) * (nx) + (size_t)(j) * (nx) + (i))
#define I3S(k, j, i, ny, nxs)  ((size_t)(k) * (ny) * (nxs) + (size_t)(j) * (nxs) + (i))
#define FADD(a, b) __fadd_rn((a), (b))
#define FMUL(a, b) __fmul_rn((a), (b))
static inline float __fadd_rn(float a, float b) { return a + b; }
static inline float __fsub_rn(float a, float b) { return a - b; }
static inline float __fmul_rn(float a, float b) { return a * b; }
static inline float __fdiv_rn(float a, float b) { return a / b; }
static inline float fmaxf(float a, float b) { return fmax(a, b); }
static inline float fminf(float a, float b) { return fmin(a, b); }
static inline float sqrtf(float x) { return as_type<float>(soft32_sqrt(as_type<uint>(x))); }
static inline float gfk_pow(float x, float y) { return as_type<float>(soft_gfk_pow_bits(as_type<uint>(x), as_type<uint>(y))); }
static inline float gfk_log(float x) { return as_type<float>(soft_gfk_log(as_type<uint>(x))); }
static inline float gfk_exp(float x) { return as_type<float>(soft_gfk_exp(as_type<uint>(x))); }
static inline HailR8 glibc_pow(HailR8 x, HailR8 y) { return hail_pow(x, y); }
// glibc exp is exp_inline with no tail; NaN is quieted first.
static inline HailR8 glibc_exp(HailR8 x) {
    if ((x.bits & 0x7fffffffffffffffUL) > 0x7ff0000000000000UL) return HailR8(x.bits | 0x8000000000000UL);
    return HailR8(sgp_exp_inline(x.bits, 0ul, 0u));
}
"""


def match_braces(text: str, start: int) -> int:
    depth, end = 1, start
    while depth:
        depth += {"{": 1, "}": -1}.get(text[end], 0)
        end += 1
    return end


def functions(text: str, header: str):
    """(name, signature, body) of every function introduced by `header` regex."""
    for match in re.finditer(header, text, re.S):
        end = match.end()
        stop = match_braces(text, end)
        yield match.group("name"), match.group("sig"), text[end:stop - 1]


def hex_array(text: str, name: str):
    body = re.search(name + r"\[\d+\]\s*=\s*\{(.*?)\};", text, re.S).group(1)
    bits = []
    for token in (t.strip() for t in body.split(",") if t.strip()):
        value = float.fromhex(token) if token.startswith("0x") else float(token)
        bits.append(struct.unpack("<Q", struct.pack("<d", value))[0])
    return bits


def operand_end(text: str, pos: int) -> int:
    match = re.match(r"\s*[A-Za-z_]\w*", text[pos:])
    end = pos + match.end()
    if text[end:end + 1] == "(":
        depth = 0
        while True:
            depth += {"(": 1, ")": -1}.get(text[end], 0)
            end += 1
            if depth == 0:
                break
    return end


def cast_to(text: str, cast: str, wrapper: str) -> str:
    while cast in text:
        index = text.index(cast)
        start = index + len(cast)
        if text[start] == "(":  # parenthesised operand
            depth, end = 0, start
            while True:
                depth += {"(": 1, ")": -1}.get(text[end], 0)
                end += 1
                if depth == 0:
                    break
        else:
            end = operand_end(text, start)
        text = text[:index] + f"{wrapper}({text[start:end].strip()})" + text[end:]
    return text


def double_literals(text: str) -> str:
    def convert(match):
        bits = struct.unpack("<Q", struct.pack("<d", float(match.group(0))))[0]
        return f"HAIL_D(0x{bits:016x}ul)"
    return re.sub(r"(?<![\w.])(?:\d+\.\d*|\.\d+)(?:[eE][+-]?\d+)?(?![\w.])", convert, text)


def device_text(text: str) -> str:
    text = text.replace("__device__ __forceinline__", "static inline").replace("__device__", "static inline")
    text = re.sub(r"const real\s*\*", "device const float*", text)
    text = re.sub(r"\breal\s*\*", "device float*", text)
    return re.sub(r"\breal\b", "float", text)


def hail_text(name: str, sig: str, body: str) -> str:
    body = double_literals(body)  # float literals carry an f suffix and are untouched
    body = cast_to(body, "(double)", "HailR8").replace("double ", "HailR8 ")
    body = cast_to(body, "(real)", "float")
    body = re.sub(r"gsd_hail_(d|width)\[([^\]]+)\]", r"HailR8(gsd_hail_\1_bits[\2])", body)
    body = re.sub(r"(\w+)\+=([^;]+);", r"\1=\1+(\2);", body)  # HailR8 has no compound assignment
    return f"static inline float {name}({device_text(sig)}) {{{device_text(body)}}}\n"


def kernels(text: str):
    pattern = r'extern "C" __global__ void (?P<name>\w+)\((?P<sig>[^)]*)\)\s*\{'
    yield from functions(text, pattern)


def translate_kernel(name, sig, body, module):
    title = "".join(part.title() for part in name.split("_"))
    resources, scalars, alias = [], [], []
    for decl in (" ".join(p.split()) for p in sig.replace("\n", " ").split(",")):
        if not decl:
            continue
        pointer = "*" in decl
        tokens = re.findall(r"[A-Za-z_]\w*", decl)
        field, ctype = tokens[-1], [t for t in tokens[:-1] if t != "const"][0]
        const = "const" in tokens
        if pointer:
            resources.append([field, "float", "read" if const else "read_write"])
            alias.append(f"    device {'const ' if const else ''}float* {field} = r.{field};")
        else:
            scalars.append([field, "int32" if ctype == "int" else "float32"])
            alias.append(f"    {'int' if ctype == 'int' else 'float'} {field} = prm.{field};")
    body = body.replace("blockIdx.x*blockDim.x+threadIdx.x", "int(tid)")
    body = device_text(body)
    shader = (f"kernel void {name}(constant {title}Resources &r [[buffer(0)]],\n"
              f"    constant {title}Params &prm [[buffer(1)]],\n"
              f"    uint tid [[thread_position_in_grid]]) {{\n" + "\n".join(alias) + body + "}\n")
    shapes = {}
    for field, _, _ in resources:
        if name == "gsd_lightning3" and field in PLANE_BY_LENGTH:
            shapes[field] = [["any_2d"]]
        else:
            shapes[field] = SHAPES.get(field, PLANE)
    fragment = {
        "name": name, "module": module, "source": "woof/metal/shaders/gsd_diagnostics_family.metal",
        "cuda_source": f"woof/core/kernels/{module}.cu", "cuda_symbol": name,
        "resources": resources, "shapes": shapes, "parameters": scalars,
        "threads_per_group": 128, "layout_version": 1, "arithmetic_policies": ["default"],
    }
    return shader, fragment


def main():
    cu = (KERNELS / "gsd_diagnostics.cu").read_text()
    helicity = (KERNELS / "gsd_helicity.cu").read_text()
    helpers = (KERNELS / "gsd_helicity_helpers.cuh").read_text()
    bins = (KERNELS / "gsd_hail_bins.cuh").read_text()
    extra = (KERNELS / "glibc_flt32_extra.cuh").read_text()

    parts, fragments, names = [], [], []
    for const in ("gsd_hail_d", "gsd_hail_width"):
        words = ", ".join(f"0x{bits:016x}ul" for bits in hex_array(bins, "double " + const))
        parts.append(f"constant ulong {const}_bits[50] = {{{words}}};\n")
    parts.extend(l + "\n" for l in cu.splitlines() if l.startswith("#define"))
    for name, header in (("gfk_subnormal_times_2p25", r"__device__ __forceinline__ unsigned int (?P<name>gfk_subnormal_times_2p25)\((?P<sig>[^)]*)\)\s*\{"),
                         ("gfk_log10", r"__device__ float (?P<name>gfk_log10)\((?P<sig>[^)]*)\)\s*\{")):
        for fname, sig, body in functions(extra, header):
            ret = "uint" if fname.startswith("gfk_sub") else "float"
            body = (body.replace("__clz((int)m)", "clz(int(m))").replace("__int_as_float", "as_type<float>")
                    .replace("__float_as_int", "as_type<int>").replace("fabsf", "fabs")
                    .replace("unsigned int", "uint"))
            sig = sig.replace("unsigned int", "uint")
            parts.append(f"static inline {ret} {fname}({sig}) {{{body}}}\n")
    for fname, sig, body in functions(helpers, r"__device__ __forceinline__ real (?P<name>\w+)\((?P<sig>[^)]*)\)\s*\{"):
        parts.append(f"static inline float {fname}({device_text(sig)}) {{{device_text(body)}}}\n")
    for fname, sig, body in functions(cu, r"__device__ real (?P<name>gd_\w+)\((?P<sig>[^)]*)\)\s*\{"):
        parts.append(hail_text(fname, sig, body) if fname == "gd_hail" else
                     f"static inline float {fname}({device_text(sig)}) {{{device_text(body)}}}\n")
    for text, module in ((cu, "gsd_diagnostics"), (helicity, "gsd_helicity")):
        for name, sig, body in kernels(text):
            if name in SKIP:
                continue
            shader, fragment = translate_kernel(name, sig, body, module)
            parts.append(shader)
            fragments.append(fragment)
            names.append(name)
    includes = "\n".join(f'#include "{n}_bindings.metalh"' for n in names)
    SHADER.write_text(PRELUDE % {"includes": includes} + "\n" + "\n".join(parts), encoding="utf-8")
    FRAGMENT.write_text(json.dumps({"kernels": fragments}, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
