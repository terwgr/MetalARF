#!/usr/bin/env python3
"""Generate resident grid/chunk copies for the Goddard column solver."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[2]
FIELDS=('pw','temperature','pressure','qv','cldfra','dz','rho','qi','qc','qr','qs','qg','qh',
        're_ice','re_cloud','re_rain','re_snow','re_graupel','re_hail',
        'latitude','cosine','tw','tsk','emiss','albedo','exner')

def signature(name,resources,parameters):
 return dict(name=name,cuda_symbol=name,module='goddard_grid',
  source='woof/metal/shaders/goddard_grid.metal',cuda_source='woof/core/kernels/goddard.cu',
  resources=resources,shapes={r[0]:[['any_1d']] for r in resources},
  parameters=parameters,threads_per_group=128,layout_version=1,
  arithmetic_policies=['native32-rn-nonftz'])

def main():
 common=[['np','int32'],['full_columns','int32'],['first','int32'],['columns','int32']]
 sigs=[signature('goddard_pack_grid',[[f,'float','read'] for f in FIELDS]+[['raw','float','read_write']],common+[['direct_radii','int32']]),
       signature('goddard_scatter_grid',[[f,'float','read' if f=='input' else 'read_write'] for f in ('input','heat_lw','heat_sw','surface')],common)]
 parts=['// Generated by tools/goddard_metal/generate_grid.py.','#include <metal_stdlib>',
        '#include "goddard_grid_bindings.metalh"','using namespace metal;','#pragma clang fp contract(off)']
 for s in sigs:
  title=''.join(x.title() for x in s['name'].split('_'))
  parts.append('kernel void '+s['name']+'(constant '+title+'Resources&r [[buffer(0)]],constant '+title+'Params&p [[buffer(1)]],uint gid [[thread_position_in_grid]]){')
  parts.append('const uint columns=uint(p.columns), np=uint(p.np);')
  if s['name']=='goddard_pack_grid':
   parts.append('if(gid >= (20u*np+7u)*columns)return;\nconst uint row=gid/columns, col=uint(p.first)+gid%columns;\nconst uint full=uint(p.full_columns);\nfloat value;\nif(row<np+1u)value=r.pw[row*full+col];\nelse if(row<19u*np+1u){\nconst uint block=(row-np-1u)/np, level=(row-np-1u)%np;\nconst uint at=level*full+col;\nswitch(block){')
   for i,f in enumerate(FIELDS[1:19]):parts.append('case '+str(i)+'u:value=r.'+f+'[at];break;')
   parts.append('default:value=0.0f;break;}\nif(block>=12u && p.direct_radii==0)value=(value*1.e-6f)*1.e6f;\n}else if(row<19u*np+7u){\nswitch(row-(19u*np+1u)){')
   for i,f in enumerate(('latitude','cosine','tw','tsk','emiss','albedo')):parts.append('case '+str(i)+'u:value=r.'+f+'[col];break;')
   parts.append('default:value=0.0f;break;}\n}else value=r.exner[(row-(19u*np+7u))*full+col];\nr.raw[gid]=value;')
  else:
   parts.append('if(gid >= (2u*np+15u)*columns)return;\nconst uint row=gid/columns, col=uint(p.first)+gid%columns;\nconst uint full=uint(p.full_columns);\nif(row<np)r.heat_lw[row*full+col]=r.input[gid];\nelse if(row<2u*np)r.heat_sw[(row-np)*full+col]=r.input[gid];\nelse r.surface[(row-2u*np)*full+col]=r.input[gid];')
  parts.append('}')
 (ROOT/'woof/metal/shaders/goddard_grid.metal').write_text('\n'.join(parts)+'\n')
 (ROOT/'woof/metal/signature_fragments/goddard_grid.json').write_text(json.dumps({'kernels':sigs},indent=2)+'\n')

if __name__=='__main__':main()
