#!/usr/bin/env python3
"""Generate the WRF 4.6.1 aerosol reflectivity Metal transcription."""
import json
import sys
from pathlib import Path
# The shared translator is delivered with the mp=28 source networks.
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
import generate as g

def main():
    g.PROVIDED = {'glibc_exp', 'glibc_log', 'glibc_pow'}
    items = g.items_of('thompson_aerosol_state', '461')
    reached, _ = g.closure(items, ['thompson_aa_refl10cm'])
    reached = [g.typed_nulls(it, reached) for it in reached]
    helper_text = []
    kernel = None
    for it in reached:
        kind = g.kind_of(it)
        if kind == 'kernel':
            if g.def_name(it) == 'thompson_aa_refl10cm':
                kernel = it
        elif kind == 'struct':
            helper_text.append(g.convert_struct(it))
        elif kind == 'table':
            helper_text.append(g.convert_table(it))
        else:
            helper_text.append(g.convert_function_item(it))
    if kernel is None:
        raise RuntimeError('reflectivity kernel not found')
    text, params = g.convert_kernel(kernel, 'thompson_aa_refl10cm', 'aa_refl', [])
    # These three aliases retain the device address space of the table buffer.
    text = text.replace('const Soft8 * xx', 'device const Soft8 * xx')
    text = text.replace('const Soft8 * xd', 'device const Soft8 * xd')
    text = text.replace('const Soft8 * simpson', 'device const Soft8 * simpson')
    resources, shapes, parameters = [], {}, []
    for prm in params:
        if prm['pointer']:
            storage = 'float64_bits' if prm['base'] == 'double' else 'float'
            resources.append([prm['name'], storage, 'read' if prm['const'] else 'read_write'])
            shapes[prm['name']] = [['any_1d']]
        else:
            parameters.append([prm['name'], 'int32'])
    shader = ROOT/'woof/metal/shaders/thompson_aerosol_refl_family.metal'
    fragment = ROOT/'woof/metal/shaders/thompson_aerosol_refl_fragment.metalh'
    fragment.write_text('// Generated from woof/core/kernels/thompson_aerosol_state.cu\n'
                        '// by tools/mp28_metal/generate_reflectivity.py; do not edit.\n'
                        '#pragma clang fp contract(off)\nnamespace aa_refl {\n'
                        + '\n'.join(helper_text) + '\n}\n')
    shader.write_text('// Generated by tools/mp28_metal/generate_reflectivity.py; do not edit.\n'
                      '#include <metal_stdlib>\n'
                      '#include "thompson_aerosol_soft8.metalh"\n'
                      '#include "thompson_aerosol_refl_fragment.metalh"\n'
                      '#include "thompson_aerosol_refl_family_bindings.metalh"\n'
                      + text + '\n')
    signature = {'name': 'thompson_aa_refl10cm', 'cuda_symbol': 'thompson_aa_refl10cm',
                 'module': 'thompson_aerosol_refl_family', 'source': 'woof/metal/shaders/'+shader.name,
                 'cuda_source': 'woof/core/kernels/thompson_aerosol_state.cu',
                 'resources': resources, 'shapes': shapes, 'parameters': parameters,
                 'threads_per_group': 32, 'layout_version': 1,
                 'arithmetic_policies': g.POLICIES}
    (ROOT/'woof/metal/signature_fragments/thompson_aerosol_refl_family.json').write_text(
        json.dumps({'kernels': [signature]}, indent=2)+'\n')

if __name__ == '__main__':
    main()
