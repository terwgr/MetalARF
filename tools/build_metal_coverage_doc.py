#!/usr/bin/env python3
"""Generate the guide's selector table from Metal's admission registry (CPU only)."""
from __future__ import annotations
import argparse, ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
START = '<!-- metal-capabilities:start -->'
END = '<!-- metal-capabilities:end -->'
LABELS = {
    'mp': 'Microphysics (`mp_physics`)',
    'pbl': 'PBL (`bl_pbl_physics`)',
    'mynn_version': 'MYNN source form (`bl_mynn_version`)',
    'sfclay': 'Surface layer (`sf_sfclay_physics`)',
    'lsm': 'Land surface (`sf_surface_physics`)',
    'cu': 'Cumulus (`cu_physics`)',
    'ra': 'Radiation (LW, SW)',
    'urban': 'Urban (`sf_urban_physics`)',
}


def table() -> str:
    # Reading the literal registry avoids importing physics or allocating a device.
    tree = ast.parse((ROOT/'woof/core/physics.py').read_text())
    expression = next(n.value for n in tree.body if isinstance(n, ast.Assign)
                      and any(isinstance(t, ast.Name) and t.id == 'METAL_FAMILY_CAPS' for t in n.targets))
    caps = {}
    for key, value in zip(expression.keys, expression.values):
        if not (isinstance(value, ast.Call) and isinstance(value.func, ast.Name)
                and value.func.id == 'frozenset' and len(value.args) == 1 and not value.keywords):
            raise ValueError('Admission registry shape changed; update this documentation reader.')
        caps[ast.literal_eval(key)] = frozenset(ast.literal_eval(value.args[0]))
    if set(caps) != set(LABELS):
        raise ValueError('Admission families changed; update the selector labels.')
    lines = [START, '<!-- Generated by tools/build_metal_coverage_doc.py; caller availability, not parity. -->',
             '| Family | Selectors listed by Metal admission |', '|---|---|']
    for key, label in LABELS.items():
        values = ', '.join(f'`{v}`' if isinstance(v, str) else str(v) for v in sorted(caps[key]))
        lines.append(f'| {label} | {values} |')
    return '\n'.join(lines+[END])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='refuse a stale table without changing it')
    args = parser.parse_args(); path = ROOT/'docs/public/BACKENDS.md'; text = path.read_text()
    if START in text:
        begin = text.index(START); end = text.index(END, begin)+len(END)
    else:
        begin = text.index('| Family | Selectors listed by Metal admission |')
        end = text.index('\n\n', begin)
    updated = text[:begin]+table()+text[end:]
    if args.check:
        if updated != text:
            print('Metal selector table is stale; run tools/build_metal_coverage_doc.py')
            return 1
        print('Metal selector table matches METAL_FAMILY_CAPS.')
        return 0
    path.write_text(updated); print('Updated docs/public/BACKENDS.md from METAL_FAMILY_CAPS.'); return 0

if __name__ == '__main__':raise SystemExit(main())
